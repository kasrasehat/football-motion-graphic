// Generates src/generated/render_props.ts from schemas/artifacts/render_props.schema.json.
// Usage: node scripts/gen-types.mjs            (write)
//        node scripts/gen-types.mjs --check    (exit 1 if the checked-in file is stale)
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const schemaPath = join(root, "..", "schemas", "artifacts", "render_props.schema.json");
const outPath = join(root, "src", "generated", "render_props.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

// Codegen-only adjustments on an in-memory copy (the schema file itself is never modified):
// 1. name the root and the main sub-objects so the generated types are usable by name;
// 2. json-schema-to-typescript predates Draft 2020-12 `prefixItems`, so map it to the equivalent tuple `items` form.
delete schema.$id;
schema.title = "RenderProps";
const P = schema.properties;
const named = [
  [P.theme, "Theme"],
  [P.tracks, "Tracks"],
  [P.entities.items, "Entity"],
  [P.scenes.items, "Scene"],
  [P.overlays.items, "Overlay"],
  [P.overlays.items.properties.style, "OverlayStyle"],
  [P.graphics.items, "Graphic"],
  [P.captions.items, "Caption"],
  [P.principleRail, "PrincipleRail"],
  [P.captions.items.properties.words.items, "CaptionWord"],
  [P.titleCard.anyOf[1], "TitleCard"],
  [P.endCard.anyOf[1], "EndCard"],
];
for (const [node, title] of named) node.title = title;
const geom = P.overlays.items.properties.geom;
geom.oneOf[0].title = "StaticGeom";
geom.oneOf[1].title = "PerFrameGeom";

function mapPrefixItems(node) {
  if (Array.isArray(node)) return node.forEach(mapPrefixItems);
  if (!node || typeof node !== "object") return;
  if (node.prefixItems && node.items === undefined) {
    node.items = node.prefixItems;
    delete node.prefixItems;
  }
  for (const v of Object.values(node)) mapPrefixItems(v);
}
mapPrefixItems(schema);

const banner =
  "/* GENERATED by `npm run gen:types` from schemas/artifacts/render_props.schema.json — do not edit by hand. */";
let ts = await compile(schema, "RenderProps", {
  bannerComment: banner,
  unknownAny: true,
  strictIndexSignatures: false,
  format: true,
  style: { printWidth: 120, singleQuote: false, semi: true, trailingComma: "all" },
  cwd: dirname(schemaPath),
});
ts = ts.replace(/\r\n/g, "\n");

const check = process.argv.includes("--check");
if (check) {
  const cur = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== ts) {
    console.error("gen:types: src/generated/render_props.ts is STALE — run `npm run gen:types` and commit the result");
    process.exit(1);
  }
  console.log("gen:types: up to date");
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, ts, "utf8");
  console.log(`gen:types: wrote ${outPath}`);
}
