"""Generate harness mirrors from canonical sources.

  skills/<name>/**        -> .claude/skills/<name>/**   (Claude Code)
                          -> .agents/skills/<name>/**   (Codex; + agents/openai.yaml for user-only skills)
  agents/<name>.md        -> .claude/agents/<name>.md   (Claude Code subagent)
                          -> .codex/agents/<name>.toml  (Codex custom agent)
  generated doc blocks    -> AGENTS.md (index), PROJECT_CONTEXT.md (stages)

Canonical skill frontmatter: name, description, optional `harness: {user_only: bool, allowed_tools: str}`.
Canonical agent frontmatter: name, description, tools (Claude tool list), effort (low|medium|high), optional model.
"""
from __future__ import annotations

import json
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

import yaml

from tms import manifest, paths

MARK_MD = "<!-- GENERATED by `tms sync-harness` from {src} — do not edit; edit the source and re-run -->"
MARK_TOML = "# GENERATED by `tms sync-harness` from {src} — do not edit; edit the source and re-run"
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
FRONT_RE = re.compile(r"^---\n(.*?)\n---\n(.*)$", re.S)
EFFORTS = ("low", "medium", "high")


class SyncError(Exception):
    pass


@dataclass
class Doc:
    meta: dict
    body: str


def parse_front(text: str, src: str) -> Doc:
    m = FRONT_RE.match(text.replace("\r\n", "\n"))
    if not m:
        raise SyncError(f"{src}: missing YAML frontmatter")
    meta = yaml.safe_load(m.group(1)) or {}
    return Doc(meta, m.group(2).lstrip("\n"))


def _check_common(meta: dict, expected_name: str, src: str) -> None:
    name, desc = meta.get("name"), meta.get("description")
    if name != expected_name:
        raise SyncError(f"{src}: name {name!r} must equal {expected_name!r}")
    if not NAME_RE.match(name) or len(name) > 64:
        raise SyncError(f"{src}: invalid name {name!r} (lowercase, digits, single hyphens, <= 64)")
    if not isinstance(desc, str) or not 20 <= len(desc) <= 1024 or "<" in desc or ">" in desc:
        raise SyncError(f"{src}: description must be 20-1024 chars without < or >")


def _front(meta: dict) -> str:
    return "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000).strip() + "\n---\n"


def _toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # TOML basic strings accept JSON escapes


def _toml_multiline(s: str) -> str:
    if "'''" not in s:
        return "'''\n" + s.rstrip("\n") + "\n'''"
    return '"""\n' + s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').rstrip("\n") + '\n"""'


# ----------------------------------------------------------------- planning
def planned_outputs() -> dict[Path, bytes]:
    root = paths.root()
    out: dict[Path, bytes] = {}
    for sdir in sorted((root / "skills").glob("*/")):
        if not (sdir / "SKILL.md").is_file():
            continue
        name = sdir.name
        src = f"skills/{name}/SKILL.md"
        doc = parse_front((sdir / "SKILL.md").read_text(encoding="utf-8"), src)
        _check_common(doc.meta, name, src)
        extra = set(doc.meta) - {"name", "description", "harness"}
        if extra:
            raise SyncError(f"{src}: unsupported frontmatter keys {sorted(extra)}")
        h = doc.meta.get("harness") or {}
        body = MARK_MD.format(src=src) + "\n\n" + doc.body
        claude_meta = {"name": name, "description": doc.meta["description"]}
        if h.get("user_only"):
            claude_meta["disable-model-invocation"] = True
        if h.get("allowed_tools"):
            claude_meta["allowed-tools"] = h["allowed_tools"]
        codex_meta = {"name": name, "description": doc.meta["description"]}
        out[root / ".claude/skills" / name / "SKILL.md"] = (_front(claude_meta) + "\n" + body).encode()
        out[root / ".agents/skills" / name / "SKILL.md"] = (_front(codex_meta) + "\n" + body).encode()
        if h.get("user_only"):
            first = doc.meta["description"].split(". ")[0].split(" (")[0]
            short = first if len(first) <= 120 else first[:117].rsplit(" ", 1)[0] + "..."
            oy = {"interface": {"display_name": name.replace("-", " ").title(),
                                "short_description": short},
                  "policy": {"allow_implicit_invocation": False}}
            out[root / ".agents/skills" / name / "agents/openai.yaml"] = \
                ("# " + MARK_TOML.format(src=src)[2:] + "\n" + yaml.safe_dump(oy, sort_keys=False)).encode()
        for f in sorted(sdir.rglob("*")):
            if f.is_file() and f.name != "SKILL.md":
                rel = f.relative_to(sdir)
                data = f.read_bytes()
                out[root / ".claude/skills" / name / rel] = data
                out[root / ".agents/skills" / name / rel] = data
    for af in sorted((root / "agents").glob("*.md")):
        name = af.stem
        src = f"agents/{name}.md"
        doc = parse_front(af.read_text(encoding="utf-8"), src)
        _check_common(doc.meta, name, src)
        extra = set(doc.meta) - {"name", "description", "tools", "effort", "model"}
        if extra:
            raise SyncError(f"{src}: unsupported frontmatter keys {sorted(extra)}")
        if doc.meta.get("effort", "medium") not in EFFORTS:
            raise SyncError(f"{src}: effort must be one of {EFFORTS}")
        if not isinstance(doc.meta.get("tools"), list) or not doc.meta["tools"]:
            raise SyncError(f"{src}: tools must be a non-empty list")
        cm = {"name": name, "description": doc.meta["description"], "tools": ", ".join(doc.meta["tools"])}
        if doc.meta.get("model"):
            cm["model"] = doc.meta["model"]
        out[root / ".claude/agents" / f"{name}.md"] = (_front(cm) + "\n" + MARK_MD.format(src=src) + "\n\n" + doc.body).encode()
        toml = "\n".join([
            MARK_TOML.format(src=src),
            f"name = {_toml_str(name)}",
            f"description = {_toml_str(doc.meta['description'])}",
            f"model_reasoning_effort = {_toml_str(doc.meta.get('effort', 'medium'))}",
            f"developer_instructions = {_toml_multiline(doc.body)}",
            "",
        ])
        out[root / ".codex/agents" / f"{name}.toml"] = toml.encode()
    for doc_path, block, content in generated_blocks():
        text = doc_path.read_text(encoding="utf-8") if doc_path.is_file() else ""
        out[doc_path] = replace_block(text, block, content, doc_path).encode()
    return {p: (b.replace(b"\r\n", b"\n")) for p, b in out.items()}


GENERATED_DIRS = (".claude/skills", ".agents/skills", ".claude/agents", ".codex/agents")


def _existing_generated() -> set[Path]:
    root = paths.root()
    found = set()
    for d in GENERATED_DIRS:
        base = root / d
        if base.is_dir():
            found |= {f for f in base.rglob("*") if f.is_file()}
    return found


# ----------------------------------------------------------------- doc blocks
def replace_block(text: str, block: str, content: str, where: Path) -> str:
    begin, end = f"<!-- BEGIN GENERATED:{block} -->", f"<!-- END GENERATED:{block} -->"
    if begin not in text or end not in text:
        raise SyncError(f"{where.name}: missing markers for generated block '{block}'")
    pre, rest = text.split(begin, 1)
    _, post = rest.split(end, 1)
    return f"{pre}{begin}\n{content.rstrip()}\n{end}{post}"


def _stage_table() -> str:
    lines = []
    for mode in manifest.modes():
        lo, hi, d = manifest.duration_range(mode)
        lines += [f"**Mode `{mode}`** — {manifest.load()['modes'][mode]['title']} ({lo}–{hi} s, default {d} s)", "",
                  "| # | Stage | Gate | Produces | Inputs | QA reviewers | Skill |", "|---|---|---|---|---|---|---|"]
        for i, s in enumerate(manifest.mode_stages(mode), 1):
            gate = f"human: `approve {manifest.approval_word(s)}`" if manifest.gate(s) == "human" else "auto"
            if manifest.is_optional(s):
                gate += " (optional)"
            qa = ", ".join(f"{q['agent']} ({q['min_rounds']}–{q['max_rounds']})" for q in manifest.stage_qa(s, mode)) or "–"
            lines.append(f"| {i} | `{s}` | {gate} | {', '.join(manifest.stage_produces(s))} | "
                         f"{', '.join(manifest.stage_inputs(s, mode)) or '–'} | {qa} | `{manifest.stage(s)['skill']}` |")
        lines.append("")
    return "\n".join(lines)


def _index() -> str:
    root = paths.root()
    lines = ["**Skills** (`skills/` canonical → `.claude/skills/`, `.agents/skills/`)", ""]
    for sdir in sorted((root / "skills").glob("*/")):
        f = sdir / "SKILL.md"
        if f.is_file():
            meta = parse_front(f.read_text(encoding="utf-8"), str(f)).meta
            lines.append(f"- `{sdir.name}` — {meta['description'].split('. ')[0].rstrip('.')}.")
    lines += ["", "**Subagents** (`agents/` canonical → `.claude/agents/`, `.codex/agents/`)", ""]
    for af in sorted((root / "agents").glob("*.md")):
        meta = parse_front(af.read_text(encoding="utf-8"), str(af)).meta
        lines.append(f"- `{af.stem}` — {meta['description'].split('. ')[0].rstrip('.')}.")
    return "\n".join(lines)


def generated_blocks() -> list[tuple[Path, str, str]]:
    root = paths.root()
    return [(root / "PROJECT_CONTEXT.md", "stages", _stage_table()), (root / "AGENTS.md", "index", _index())]


# ----------------------------------------------------------------- apply / check
def sync(check: bool = False) -> list[str]:
    planned = planned_outputs()
    drift: list[str] = []
    for p, data in planned.items():
        cur = p.read_bytes().replace(b"\r\n", b"\n") if p.is_file() else None
        if cur != data:
            drift.append(p.relative_to(paths.root()).as_posix())
            if not check:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(data)
    for stale in sorted(_existing_generated() - set(planned)):
        drift.append(stale.relative_to(paths.root()).as_posix() + " (stale)")
        if not check:
            stale.unlink()
    if not check:
        for d in GENERATED_DIRS:
            base = paths.root() / d
            for sub in sorted(base.rglob("*"), reverse=True) if base.is_dir() else []:
                if sub.is_dir() and not any(sub.iterdir()):
                    sub.rmdir()
    return drift


def cmd_sync(args) -> int:
    try:
        drift = sync(check=args.check)
    except SyncError as e:
        print(f"ERROR: {e}")
        return 1
    if args.check:
        if drift:
            print("out of date:\n  " + "\n  ".join(drift))
            return 1
        print("harness mirrors up to date")
        return 0
    print(f"synced {len(drift)} file(s)" + (":\n  " + "\n  ".join(drift) if drift else ""))
    return 0


def register(sub) -> None:
    p = sub.add_parser("sync-harness", help="generate .claude/ and Codex mirrors of skills/agents + doc blocks")
    p.add_argument("--check", action="store_true", help="exit 1 if anything is out of date (no writes)")
    p.set_defaults(func=cmd_sync)
